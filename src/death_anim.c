static const uint8_t s_black_row[21] = {
    240,240,240,240,240,240,240,240,240,240,
    240,240,240,240,240,240,240,240,240,240,
    240
};

// "GAME OVER" centred in 20 columns (black, GAME, space, OVER, black)

static const uint8_t s_gameover_row[21] = {
    240,240,240,240,240,240,240,
    241,242,243,244,
    240,
    245,246,244,247,
    240,240,240,240,240
};

static uint8_t s_da_timer;

void death_anim_start(void)
{
    uint8_t i = 0;

    while (i < 40) {
        move_sprite(i, 0, 0);
        i++;
    }
    set_bkg_data(DA_TILE_BASE, DA_NB_TILES, s_da_tiles);
    i = 0;
    while (i < 18) {
        set_win_tiles(0, i, 21, 1, s_black_row);
        i++;
    }
    set_win_tiles(0, DA_TEXT_ROW, 21, 1, s_gameover_row);
    move_win(0, 144);
    SHOW_WIN;
    s_da_timer = 0;
}

da_result_t death_anim_update(const input_state *input)
{
    uint8_t pressed;

    if (s_da_timer < DA_CURTAIN_FRAMES) {
        s_da_timer++;
        move_win(0, 144 - s_da_timer * DA_CURTAIN_STEP);
        SCY_REG += 2;
        return DA_RUNNING;
    }
    pressed = get_just_pressed(input);
    if (pressed & J_A) {
        HIDE_WIN;
        move_bkg(0, 0);
        return DA_RESTART;
    }
    if (pressed & J_START) {
        HIDE_WIN;
        move_bkg(0, 0);
        return DA_MENU;
    }
    return DA_RUNNING;
}
